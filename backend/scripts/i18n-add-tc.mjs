const FILES = ["zh-CN", "zh-TW", "en-US"];
const counts = {};
for (const lang of FILES) {
  const p = path.join(I18N, `${lang}.json`);
  const dict = JSON.parse(readFileSync(p, "utf8"));
  Object.assign(dict, KEYS[lang]);
  const sorted = {};
  for (const k of Object.keys(dict).sort()) sorted[k] = dict[k];
  writeFileSync(p, JSON.stringify(sorted, null, 2) + "\n", "utf8");
  counts[lang] = Object.keys(sorted).length;
}
copyFileSync(path.join(I18N, "zh-CN.json"), path.join(I18N, "fallback.json"));
counts["fallback"] = counts["zh-CN"];

const expect = new Set(Object.values(counts));
if (expect.size !== 1) {
  console.error("KEY COUNT MISMATCH", counts);
  process.exit(1);
}
